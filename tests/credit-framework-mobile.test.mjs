import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const read = file => readFile(new URL('../' + file, import.meta.url), 'utf8');
test('manifest uses scoped same-origin resources and valid PNG dimensions', async () => {
  const manifest = JSON.parse(await read('preview/credit-framework.webmanifest'));
  assert.equal(manifest.start_url, '/preview/credit-framework.html');
  assert.equal(manifest.id, manifest.start_url);
  assert.equal(manifest.scope, '/preview/');
  assert.equal(manifest.display, 'standalone');
  assert.equal(manifest.prefer_related_applications, false);
  for (const size of [192, 512]) {
    const icon = manifest.icons.find(i => i.sizes === `${size}x${size}`);
    assert.ok(icon.src.startsWith('/assets/icons/credit-framework/'));
    const png = await readFile(new URL('..' + icon.src, import.meta.url));
    assert.equal(png.subarray(1,4).toString(), 'PNG');
    assert.equal(png.readUInt32BE(16), size);
    assert.equal(png.readUInt32BE(20), size);
  }
  const html = await read('preview/credit-framework.html');
  assert.match(html, /manifest-src 'self'/);
  assert.match(html, /connect-src 'none'/);
  assert.match(html, /rel="manifest" href="\/preview\/credit-framework.webmanifest"/);
  assert.match(html, /rel="apple-touch-icon"/);
  assert.ok(html.indexOf('credit-framework-mobile.css') > html.indexOf('</style>'));
  const js = await read('assets/js/preview/credit-framework/mobile.js');
  assert.doesNotMatch(js, /localStorage|sessionStorage|indexedDB|caches\.|serviceWorker|\bfetch\s*\(/);
  const css = await read('assets/css/credit-framework-mobile.css');
  assert.match(css, /@media screen and \(max-width:640px\)/);
  assert.match(css, /safe-area-inset-bottom/);
  assert.match(css, /@media print/);
});
let JSDOM;
try { ({ JSDOM } = await import(process.env.CF_JSDOM_MODULE || 'jsdom')); } catch {}
const integration = JSDOM ? test : test.skip;
integration('phone navigation preserves inputs and report; rerenders, risk links, resize and install dismissal work', async () => {
  const dom = new JSDOM(await read('preview/credit-framework.html'), { url: 'https://example.test/preview/credit-framework.html', pretendToBeVisual: true });
  const { window } = dom;
  const media = { matches: true, addEventListener: (_event, cb) => { media.change = cb; } };
  window.matchMedia = query => query.includes('640px') ? media : { matches: query.includes('1100px') };
  window.HTMLElement.prototype.scrollIntoView = function () {};
  for (const key of ['window','document','Node','location']) globalThis[key] = window[key];
  await import('../assets/js/preview/credit-framework/app.js');
  await import('../assets/js/preview/credit-framework/mobile.js');
  const $ = selector => document.querySelector(selector);
  const click = selector => $(selector).click();
  const activeSteps = () => [...document.querySelectorAll('#intake-form > details.sec:not(.mobile-inactive-step)')];
  assert.equal(document.body.dataset.mobileView, 'inputs');
  assert.equal(activeSteps().length, 1);
  assert.match($('#mobile-step-label').textContent, /Step 1 of 9: Deal basics/);
  const label = $('#f-dealName');
  label.value = 'De-identified test'; label.dispatchEvent(new window.Event('input', { bubbles: true }));
  click('.mobile-step-actions button:last-child');
  assert.match($('#mobile-step-label').textContent, /Step 2 of 9/);
  click('[data-mobile-view="results"]');
  assert.equal(document.activeElement.id, 'output');
  assert.equal(document.body.dataset.mobileView, 'results');
  click('#tier-output [data-tier="comprehensive"]');
  assert.equal($('#f-dealName').value, 'De-identified test');
  assert.match($('#mobile-step-label').textContent, /Step 2 of 9/);
  click('[data-mobile-view="inputs"]');
  for (let i = 0; i < 7; i++) click('.mobile-step-actions button:last-child');
  assert.match($('#mobile-step-label').textContent, /Step 9 of 9: Risk categories/);
  click('.mobile-step-actions button:last-child');
  assert.equal(document.body.dataset.mobileView, 'results');
  document.dispatchEvent(new window.Event('credit:review-triggers'));
  assert.equal(document.body.dataset.mobileView, 'inputs');
  assert.equal(activeSteps()[0].querySelector('#f-rating').id, 'f-rating');
  click('#case-picker [data-case="custom"]');
  assert.match($('#mobile-step-label').textContent, /Step 1 of 9/);
  assert.equal($('#f-dealName').value, '');
  click('[data-mobile-view="results"]');
  [...document.querySelectorAll('#output button')].find(b => b.textContent === 'Review selected triggers →').click();
  assert.equal(document.body.dataset.mobileView, 'inputs');
  assert.match($('#mobile-step-label').textContent, /Step 9 of 9/);
  assert.equal(document.activeElement.id, 'sugg-panel');
  click('[data-mobile-view="results"]');
  const change = (selector, value, event = 'input') => {
    $(selector).value = value;
    $(selector).dispatchEvent(new window.Event(event, { bubbles: true }));
  };
  change('#risk-rating-purpose', 'red', 'change');
  change('#risk-basis-purpose', 'Purpose needs review');
  click('[data-confirm-risk="purpose"]');
  assert.match($('#risk-error-purpose').textContent, /mitigation or next step/);
  change('#risk-next-purpose', 'Obtain a breakdown');
  click('[data-confirm-risk="purpose"]');
  assert.equal($('[data-risk-readout="purpose"]').dataset.status, 'red');
  click('[data-mobile-view="inputs"]');
  for (let i = 0; i < 8; i++) click('.mobile-step-actions button:first-child');
  change('#f-dealName', 'Changed input');
  click('[data-mobile-view="results"]');
  assert.equal($('[data-risk-readout="purpose"]').dataset.status, 'not_assessed');
  assert.match($('[data-risk-readout="purpose"]').textContent, /Review required/);
  click('[data-mobile-view="install"]');
  assert.equal(document.activeElement.id, 'mobile-install');
  assert.match($('#mobile-install').textContent, /Internet access is required/);
  const event = new window.Event('beforeinstallprompt', { cancelable: true });
  let prompted = 0;
  event.prompt = async () => { prompted++; };
  event.userChoice = Promise.resolve({ outcome: 'dismissed' });
  window.dispatchEvent(event);
  assert.equal(event.defaultPrevented, true);
  assert.equal($('#mobile-install button').hidden, false);
  click('#mobile-install button');
  await new Promise(resolve => setTimeout(resolve, 0));
  assert.equal(prompted, 1);
  assert.equal($('#mobile-install button').hidden, true);
  assert.match($('#mobile-install').textContent, /Installation dismissed/);
  click('#mobile-install button'); assert.equal(prompted, 1);
  media.matches = false; media.change();
  assert.equal(document.querySelectorAll('.mobile-inactive-step').length, 0);
  media.matches = true; media.change();
  assert.equal(activeSteps().length, 1);
  dom.window.close();
});
